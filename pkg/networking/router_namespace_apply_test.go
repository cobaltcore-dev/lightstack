	"qrouter-0B1C2D3E-0000-4000-8000-00000000000C\n" +
	"qdhcp-4d5e6f70-0000-4000-8000-000000000004 (id: 9)\n"

func TestHeldRouters(t *testing.T) {
	f := &fakeRunner{respond: func(_ context.Context, c fakeCall) ([]byte, error) {
		return []byte(testNetnsList), nil
	}}
	got, err := realModeRouter(f).HeldRouters(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	// Only a qrouter- namespace named by a router id as Lightstack writes one: upstream's agent and
	// anyone else may use the prefix too.
	want := []string{"0b1c2d3e-0000-4000-8000-00000000000b", testRouterID}
	if slices.Sort(got); !slices.Equal(got, want) {
		t.Errorf("held = %q; want %q", got, want)
	}
	if cmds := f.commands(); !slices.Equal(cmds, []string{"ip netns list"}) {
		t.Errorf("commands %q; want the namespaces listed once", cmds)
	}

	t.Run("a failed listing is an error, not a node holding none", func(t *testing.T) {
		f := &fakeRunner{respond: func(context.Context, fakeCall) ([]byte, error) { return nil, errors.New("exit status 1") }}
		if _, err := realModeRouter(f).HeldRouters(context.Background()); err == nil {
			t.Fatal("no error")
		}
	})

	t.Run("stub mode holds none and runs nothing", func(t *testing.T) {
		f := &fakeRunner{}
		rm := NewRouterManager("stub")
		rm.run = f.run
		if got, err := rm.HeldRouters(context.Background()); err != nil || len(got) != 0 || len(f.calls) != 0 {
			t.Errorf("= %q, %v after %q; want none, nothing run", got, err, f.commands())
		}
	})
}

// strayNode answers as a network node whose uplink proxies four addresses: one a router's leg routes,
// one routed elsewhere, one nothing routes, and one outside Lightstack's records.
func strayNode(_ context.Context, c fakeCall) ([]byte, error) {
	switch c.name + " " + strings.Join(c.args, " ") {
	case "ip -j neigh show proxy dev " + testUplink:
		return []byte(`[{"dst":"203.0.113.5","dev":"eth0","flags":["proxy"]},` +
			`{"dst":"203.0.113.6","dev":"eth0","flags":["proxy"]},` +
			`{"dst":"203.0.113.8","dev":"eth0","flags":["proxy"]},` +
			`{"dst":"198.51.100.7","dev":"eth0","flags":["proxy"]},` +
			`{"dst":"2001:db8::5","dev":"eth0","flags":["proxy"]}]`), nil
	case "ip -4 -j route show":
		return []byte(`[{"dst":"default","gateway":"192.0.2.1","dev":"eth0"},` +
			`{"dst":"203.0.113.5","dev":"` + testLG + `","scope":"link"},` +
			`{"dst":"203.0.113.8","dev":"eth0","scope":"link"},` +
			`{"dst":"192.0.2.0/24","dev":"eth0","scope":"link"}]`), nil
	}
	return nil, nil
}

func ours(addr string) bool { return strings.HasPrefix(addr, "203.0.113.") || addr == "2001:db8::5" }

func TestRemoveStrayProxies(t *testing.T) {
	f := &fakeRunner{respond: strayNode}
	removed, err := realModeRouter(f).RemoveStrayProxies(context.Background(), testUplink, ours)
	if err != nil {
		t.Fatal(err)
	}
	// 203.0.113.5 is a router's: its leg routes it. 198.51.100.7 is not Lightstack's. An IPv6 entry is
	// never a router's: their host addresses are IPv4.
	want := []string{
		"ip -j neigh show proxy dev " + testUplink,
		"ip -4 -j route show",
		"ip neigh del proxy 203.0.113.6 dev " + testUplink,
		"ip neigh del proxy 203.0.113.8 dev " + testUplink,
	}
	if got := f.commands(); !slices.Equal(got, want) {
		t.Errorf("commands:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
	if !slices.Equal(removed, []string{"203.0.113.6", "203.0.113.8"}) {
		t.Errorf("removed = %q", removed)
	}
	for _, c := range f.calls {
		if !c.hasDeadline || c.budget > time.Second {
			t.Errorf("%s %v: deadline %v, budget %s; want at most a second", c.name, c.args, c.hasDeadline, c.budget)
		}
	}

	t.Run("the proxies are listed before the routes", func(t *testing.T) {
		// A router adding an address routes it before it proxies it, and removing one unproxies it
		// before it unroutes it: listing the proxies first never finds an entry a router is adding.
		cmds := f.commands()
		if !ascending(slices.Index(cmds, want[0]), slices.Index(cmds, want[1])) {
			t.Errorf("commands %q", cmds)
		}
	})

	t.Run("without an uplink nothing is read or removed", func(t *testing.T) {
		f := &fakeRunner{respond: strayNode}
		if removed, err := realModeRouter(f).RemoveStrayProxies(context.Background(), "", ours); err != nil || len(removed) != 0 || len(f.calls) != 0 {
			t.Errorf("= %q, %v after %q", removed, err, f.commands())
		}
	})

	t.Run("a failed read removes nothing", func(t *testing.T) {
		f := &fakeRunner{respond: func(ctx context.Context, c fakeCall) ([]byte, error) {
			if c.name+" "+strings.Join(c.args, " ") == "ip -4 -j route show" {
				return nil, errors.New("exit status 1")
			}
			return strayNode(ctx, c)
		}}
		if _, err := realModeRouter(f).RemoveStrayProxies(context.Background(), testUplink, ours); err == nil {
			t.Error("no error")
		}
		if w := writesOf(f); len(w) != 0 {
			t.Errorf("removed %q after a failed read", w)
		}
	})

	t.Run("stub mode runs nothing", func(t *testing.T) {
		f := &fakeRunner{respond: strayNode}
		rm := NewRouterManager("stub")
		rm.run = f.run
		if _, err := rm.RemoveStrayProxies(context.Background(), testUplink, ours); err != nil || len(f.calls) != 0 {
			t.Errorf("%v after %q", err, f.commands())
		}
	})
}
