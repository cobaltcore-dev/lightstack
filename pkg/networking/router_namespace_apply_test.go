// SPEC-033 T191: a pass cut short — a failing command, or the unit's deadline on a large router
// after a reboot — leaves the namespace and its legs half made. The next pass reads what they lack and
// finishes it: the sysctls, lo, each leg's bridge and both its ends up, connection tracking's liberal
// windows. A node holding the router whole is only read (TestConvergeRouter_UnchangedOnlyReads).
func TestConvergeRouter_FinishesWhatAPassCutShort(t *testing.T) {
	s := testRouter()
	f := &fakeRunner{respond: routerNode{state: &s, proxyARPOn: true, half: true}.respond}
	if err := realModeRouter(f).ConvergeRouter(context.Background(), testRouterID, &s, testUplink); err != nil {
		t.Fatalf("converge: %v", err)
	}
	want := []string{
		"ip -n " + testNS + " link set lo up",
		"ip netns exec " + testNS + " sysctl -w net.ipv4.ip_forward=1 net.ipv4.conf.all.arp_ignore=1 net.ipv4.conf.all.arp_announce=2",
	}
	for _, leg := range PlanRouter(s).Legs {
		if leg.Bridge != "" {
			want = append(want, "ip link set "+leg.Outside+" master "+leg.Bridge)
		}
		want = append(want, "ip link set "+leg.Outside+" up", "ip -n "+testNS+" link set "+leg.Inside+" up")
	}
	want = append(want, "ip netns exec "+testNS+" sysctl -w net.netfilter.nf_conntrack_tcp_be_liberal=1")
	if got := writesOf(f); !slices.Equal(got, want) {
		t.Errorf("writes:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

// SPEC-033 T212: the first gateway on a fresh node makes the host's forward chain in one restore —
// the chain declared, its two rules and the jump from FORWARD — so two routers converging at once cannot
// both find it missing and one fail with "Chain already exists", as `iptables -N` did.
func TestConvergeRouter_ForwardChainInOneRestore(t *testing.T) {
	s := testRouter()
	f := &fakeRunner{respond: routerNode{noForward: true}.respond}
	if err := realModeRouter(f).ConvergeRouter(context.Background(), testRouterID, &s, testUplink); err != nil {
		t.Fatalf("converge: %v", err)
	}
	var restore string
	for _, c := range f.calls {
		if c.name == "iptables" && slices.Contains(c.args, "-N") {
			t.Errorf("the chain made with iptables -N: %v", c.args)
		}
		if c.name == "iptables-restore" && strings.Contains(c.stdin, "ls-l3-fwd") {
			if !slices.Equal(c.args, []string{"--noflush", "--wait", "1"}) {
				t.Errorf("the forward chain's restore %v; want --noflush --wait 1", c.args)
			}
			restore = c.stdin
		}
	}
	for _, line := range []string{
		":ls-l3-fwd - [0:0]",
		"-A ls-l3-fwd -i " + testUplink + " -o lg+ -m comment --comment lightstack -j ACCEPT",
		"-A ls-l3-fwd -i lg+ -o " + testUplink + " -m comment --comment lightstack -j ACCEPT",
		"-I FORWARD 1 -m comment --comment lightstack -j ls-l3-fwd",
	} {
		if !slices.Contains(strings.Split(restore, "\n"), line) {
			t.Errorf("the forward chain's restore lacks %q:\n%s", line, restore)
		}
	}
}

func TestConvergeRouter_Bounds(t *testing.T) {
	s := testRouter()
	f := &fakeRunner{respond: routerNode{}.respond}
	if err := realModeRouter(f).ConvergeRouter(context.Background(), testRouterID, &s, testUplink); err != nil {
		t.Fatal(err)
	}
	for _, c := range f.calls {
		if !c.hasDeadline || c.budget > time.Second {
			t.Errorf("%s %v ran with deadline %v, budget %s; want at most a second", c.name, c.args, c.hasDeadline, c.budget)
		}
	}

	// The caller's deadline bounds the whole convergence, not only each command.
	ctx, cancel := context.WithTimeout(context.Background(), 300*time.Millisecond)
	defer cancel()
	f = &fakeRunner{respond: routerNode{}.respond}
	if err := realModeRouter(f).ConvergeRouter(ctx, testRouterID, &s, testUplink); err != nil {
		t.Fatal(err)
	}
	for _, c := range f.calls {
		if c.budget > 300*time.Millisecond {
			t.Errorf("%s %v had %s; want no more than the caller's 300 ms", c.name, c.args, c.budget)
		}
	}

	t.Run("a failing command fails the convergence", func(t *testing.T) {
		f := &fakeRunner{respond: func(ctx context.Context, c fakeCall) ([]byte, error) {
			if slices.Contains(c.args, "iptables-restore") {
				return []byte("iptables-restore: line 9 failed"), errors.New("exit status 1")
			}
			return routerNode{}.respond(ctx, c)
		}}
		if err := realModeRouter(f).ConvergeRouter(context.Background(), testRouterID, &s, testUplink); err == nil {
			t.Fatal("a failing restore: no error")
		}
		if w := writesOf(f); slices.ContainsFunc(w, func(c string) bool { return strings.HasPrefix(c, "ip route replace") }) {
			t.Error("the host's routes were added after the tables failed")
		}
	})

	t.Run("a blocking command fails it within about a second", func(t *testing.T) {
		f := &fakeRunner{respond: func(ctx context.Context, c fakeCall) ([]byte, error) {
			if strings.HasPrefix(strings.Join(append([]string{c.name}, c.args...), " "), "ip link add") {
				<-ctx.Done()
				return nil, ctx.Err()
			}
			return routerNode{}.respond(ctx, c)
		}}
		start := time.Now()
		err := realModeRouter(f).ConvergeRouter(context.Background(), testRouterID, &s, testUplink)
		if elapsed := time.Since(start); err == nil || elapsed > 1200*time.Millisecond {
			t.Errorf("a blocking command: err=%v after %s; want an error within about a second", err, elapsed)
		}
	})
}

