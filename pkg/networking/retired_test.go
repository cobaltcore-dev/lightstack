// retiredProc is a proc file system with this process's network namespace and a few processes: two
// dnsmasq an earlier layout started on the host, one started in a namespace, one that is not
// Lightstack's, a process that is not dnsmasq, and one whose command line reads empty.
func retiredProc(t *testing.T, configDir string) string {
	t.Helper()
	proc := t.TempDir()
	process := func(pid, netns string, argv ...string) {
		dir := filepath.Join(proc, pid)
		if err := os.MkdirAll(filepath.Join(dir, "ns"), 0o755); err != nil {
			t.Fatal(err)
		}
		cmdline := ""
		if len(argv) > 0 {
			cmdline = strings.Join(argv, "\x00") + "\x00"
		}
		if err := os.WriteFile(filepath.Join(dir, "cmdline"), []byte(cmdline), 0o644); err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink(netns, filepath.Join(dir, "ns", "net")); err != nil {
			t.Fatal(err)
		}
	}
	process("self", retiredOurNS, "lightstack")
	process("10", retiredOurNS, "dnsmasq", "--conf-file="+filepath.Join(configDir, "net-a.conf"), "--no-daemon", "--log-facility=-")
	process("11", retiredOtherNS, "dnsmasq", "--conf-file="+filepath.Join(configDir, "net-b.conf"), "--no-daemon")
	process("12", retiredOurNS, "/usr/sbin/dnsmasq", "--conf-file=/etc/dnsmasq.conf")
	process("13", retiredOurNS, "sleep", "--conf-file="+filepath.Join(configDir, "net-c.conf"))
	process("14", retiredOurNS)
	process("15", retiredOurNS, "/usr/sbin/dnsmasq", "--conf-file="+filepath.Join(configDir, "net-d.conf"))
	if err := os.WriteFile(filepath.Join(proc, "uptime"), []byte("1.0 1.0\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	return proc
}

func realModeRetired(t *testing.T, f *fakeRunner) *RetiredState {
	t.Helper()
	r := NewRetiredState("iptables")
	r.run = f.run
	r.dhcpConfigDir = filepath.Join(t.TempDir(), "configs")
	r.proc = retiredProc(t, r.dhcpConfigDir)
	return r
}

func retiredRecords() RetiredRecords {
	return RetiredRecords{
		FloatingIPs: []string{"203.0.113.5", "203.0.113.6"},
		SubnetCIDRs: []string{"10.0.0.0/24"},
	}
}

func TestRemoveRetired_RecognisedStateOnly(t *testing.T) {
	f := &fakeRunner{respond: retiredNode}
	if err := realModeRetired(t, f).Remove(context.Background(), retiredUplink, retiredRecords()); err != nil {
		t.Fatalf("remove: %v", err)
	}
	want := []string{
		// The earlier layout's host dnsmasq first, then the addresses, then the tables, the TAPs last.
		"kill 10",
		"kill 15",
		"ip -j addr show",
		"ip addr del 203.0.113.5/32 dev eth0",
		"ip addr del 10.0.0.1/24 dev " + retiredBridge,
		"iptables-save -t nat",
		"iptables-restore --noflush --wait 1",
		"iptables-save -t filter",
		"iptables-restore --noflush --wait 1",
		"ip link del tap-0a1b2c3d",
	}
	if got := f.commands(); !slices.Equal(got, want) {
		t.Errorf("commands:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
	r := restores(f)
	if len(r) != 2 {
		t.Fatalf("%d restores; want the nat table's and the filter table's", len(r))
	}
	wantNAT := "*nat\n" +
		"-D PREROUTING -d 203.0.113.5/32 -m comment --comment lightstack-fip -j DNAT --to-destination 10.0.0.5\n" +
		"-D PREROUTING -d 203.0.113.7/32 -m comment --comment lightstack-fip -j DNAT --to-destination 10.0.0.7\n" +
		"-D PREROUTING -d 203.0.113.6/32 -j DNAT --to-destination 10.0.0.6\n" +
		"-D PREROUTING -d 169.254.169.254/32 -i br-0a1b2c3d -p tcp -m tcp --dport 80 -j DNAT --to-destination 10.0.0.1:8775\n" +
		"-D OUTPUT -d 203.0.113.5/32 -m comment --comment lightstack-fip -j DNAT --to-destination 10.0.0.5\n" +
		"-D POSTROUTING -s 10.0.0.0/24 -o eth0 -j MASQUERADE\n" +
		"COMMIT\n"
	if r[0].stdin != wantNAT {
		t.Errorf("the nat restore:\n%s\nwant:\n%s", r[0].stdin, wantNAT)
	}
	// The two FORWARD accepts the earlier layout's egress SNAT wrote beside its masquerade go with it, for
	// the subnet with a record and the uplink alone, nothing else in them (SPEC-033 T278).
	wantFilter := "*filter\n" +
		"-D FORWARD -d 10.0.0.5/32 -i eth0 -j LS-NSI-10-0-0-5\n" +
		"-D FORWARD -s 10.0.0.0/24 -o eth0 -j ACCEPT\n" +
		"-D FORWARD -d 10.0.0.0/24 -i eth0 -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT\n" +
		"-F LS-NSI-10-0-0-5\n" +
		"-F LS-SG-0a1b2c3d\n" +
		"-X LS-NSI-10-0-0-5\n" +
		"-X LS-SG-0a1b2c3d\n" +
		"COMMIT\n"
	if r[1].stdin != wantFilter {
		t.Errorf("the filter restore:\n%s\nwant:\n%s", r[1].stdin, wantFilter)
	}
	for _, c := range f.calls {
		if !c.hasDeadline || c.budget > time.Second {
			t.Errorf("%s %v: deadline %v, budget %s; want at most a second", c.name, c.args, c.hasDeadline, c.budget)
		}
	}
}

// SPEC-033 T190: without records — reconciliation's way, since a tenant chooses a subnet's CIDR
// and an operator writes rules of the same shape — only what a mark or a name makes Lightstack's goes:
// the marked DNAT, the metadata DNAT of a managed bridge, the bridge's address, the chains and the TAPs.
// The unmarked DNAT, the masquerade and the uplink's /32 stay.
func TestRemoveRetired_WithoutRecordsOnlyMarksAndNames(t *testing.T) {
	f := &fakeRunner{respond: retiredNode}
	if err := realModeRetired(t, f).Remove(context.Background(), retiredUplink, RetiredRecords{}); err != nil {
		t.Fatalf("remove: %v", err)
	}
	for _, c := range f.commands() {
		if strings.Contains(c, "dev eth0") {
			t.Errorf("command %q: an uplink address no mark names went", c)
		}
	}
	r := restores(f)
	if len(r) != 2 {
		t.Fatalf("%d restores; want the nat table's and the filter table's", len(r))
	}
	wantNAT := "*nat\n" +
		"-D PREROUTING -d 203.0.113.5/32 -m comment --comment lightstack-fip -j DNAT --to-destination 10.0.0.5\n" +
		"-D PREROUTING -d 203.0.113.7/32 -m comment --comment lightstack-fip -j DNAT --to-destination 10.0.0.7\n" +
		"-D PREROUTING -d 169.254.169.254/32 -i br-0a1b2c3d -p tcp -m tcp --dport 80 -j DNAT --to-destination 10.0.0.1:8775\n" +
		"-D OUTPUT -d 203.0.113.5/32 -m comment --comment lightstack-fip -j DNAT --to-destination 10.0.0.5\n" +
		"COMMIT\n"
	if r[0].stdin != wantNAT {
		t.Errorf("the nat restore:\n%s\nwant:\n%s", r[0].stdin, wantNAT)
	}
	if strings.Contains(r[1].stdin, "ACCEPT") {
		t.Errorf("the filter restore removes a FORWARD accept no record names:\n%s", r[1].stdin)
	}
}

// A node the earlier layout never ran on, or one already cleaned, is only read.
func TestRemoveRetired_NothingToRemoveOnlyReads(t *testing.T) {
	f := &fakeRunner{respond: func(_ context.Context, c fakeCall) ([]byte, error) {
		switch c.name + " " + strings.Join(c.args, " ") {
		case "ip -j addr show":
			return []byte(`[{"ifname":"eth0","addr_info":[{"family":"inet","local":"192.0.2.10","prefixlen":24}]},` +
				`{"ifname":"` + retiredBridge + `","addr_info":[{"family":"inet6","local":"fe80::2","prefixlen":64}]}]`), nil
		case "iptables-save -t nat":
			return []byte("*nat\n:PREROUTING ACCEPT [0:0]\n-A PREROUTING -d 203.0.113.9/32 -j DNAT --to-destination 10.0.0.9\nCOMMIT\n"), nil
		case "iptables-save -t filter":
			return []byte("*filter\n:FORWARD DROP [0:0]\n:ls-filter-top - [0:0]\n-A FORWARD -j ls-filter-top\nCOMMIT\n"), nil
		}
		return nil, nil
	}}
	r := realModeRetired(t, f)
	r.proc = t.TempDir() // no processes at all
	if err := os.MkdirAll(filepath.Join(r.proc, "self", "ns"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(retiredOurNS, filepath.Join(r.proc, "self", "ns", "net")); err != nil {
		t.Fatal(err)
	}
	if err := r.Remove(context.Background(), retiredUplink, retiredRecords()); err != nil {
		t.Fatal(err)
	}
	want := []string{"ip -j addr show", "iptables-save -t nat", "iptables-save -t filter"}
	if got := f.commands(); !slices.Equal(got, want) {
		t.Errorf("commands %q; want the reads alone", got)
	}
}

// Without an uplink, what only the uplink makes recognisable stays; the rest goes.
func TestRemoveRetired_WithoutAnUplink(t *testing.T) {
	f := &fakeRunner{respond: retiredNode}
	if err := realModeRetired(t, f).Remove(context.Background(), "", retiredRecords()); err != nil {
		t.Fatal(err)
	}
	got := f.commands()
	if slices.Contains(got, "ip addr del 203.0.113.5/32 dev eth0") {
		t.Error("an address was removed from an uplink the node does not know")
	}
	r := restores(f)
	if len(r) != 2 || strings.Contains(r[0].stdin, "MASQUERADE") || !strings.Contains(r[0].stdin, "lightstack-fip") ||
		strings.Contains(r[1].stdin, "ACCEPT") {
		t.Errorf("restores %v; want the marked NAT removed and no MASQUERADE or FORWARD accept touched", r)
	}
	if !slices.Contains(got, "ip addr del 10.0.0.1/24 dev "+retiredBridge) || !slices.Contains(got, "kill 10") {
		t.Errorf("commands %q; want the bridge address and the host dnsmasq removed all the same", got)
	}
}

// A failure fails the removal and does not stop the rest: each kind of state is independent, and the
// next pass tries again.
func TestRemoveRetired_AFailureIsReportedAndTheRestGoes(t *testing.T) {
	f := &fakeRunner{respond: func(ctx context.Context, c fakeCall) ([]byte, error) {
		if c.name == "iptables-restore" && strings.HasPrefix(c.stdin, "*nat") {
			return []byte("iptables-restore: line 2 failed"), errors.New("exit status 1")
		}
		return retiredNode(ctx, c)
	}}
	err := realModeRetired(t, f).Remove(context.Background(), retiredUplink, retiredRecords())
	if err == nil || !strings.Contains(err.Error(), "nat") {
		t.Errorf("err = %v; want the nat table's failure", err)
	}
	if got := f.commands(); !slices.Contains(got, "iptables-save -t filter") || !slices.Contains(got, "ip link del tap-0a1b2c3d") {
		t.Errorf("commands %q; want the filter table and the TAPs handled after the nat failure", got)
	}
}

